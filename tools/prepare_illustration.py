"""Cut an original AI-generated GitRex dinosaur illustration into scene layers.

Input is assets/ai_generated_scene_source.png: a NEW in-session AI-generated
GitRex illustration crop, not the previously uploaded user reference image.
The original design has small UI elements; the output excludes all UI panels.
This optional asset-preparation step requires numpy and opencv-python.
Runtime rendering needs only Pillow. It does not contact the internet.
"""
from pathlib import Path
import cv2
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets'/'ai_generated_scene_source.png'

def main():
    img=cv2.imread(str(SOURCE),cv2.IMREAD_COLOR)
    if img is None:raise RuntimeError('Missing source illustration')
    h,w=img.shape[:2]
    if (w,h)!=(1160,530):raise RuntimeError('Unexpected art source dimensions')
    outline=np.array([
        (96,382),(111,345),(132,319),(167,293),(195,277),(244,257),(294,241),(357,222),(414,202),(462,192),(505,183),(545,168),(588,153),(628,140),(657,124),(692,123),(717,133),(745,130),(772,120),(796,107),(826,95),(858,88),(885,95),(910,96),(935,107),(965,116),(987,131),(1008,148),(1029,160),(1023,187),(1009,201),(984,211),(983,223),(1003,247),(997,263),(976,278),(961,281),(946,265),(930,251),(909,241),(895,260),(865,274),(838,280),(820,292),
        (804,311),(789,334),(783,342),(762,344),(754,337),(746,332),(736,344),(729,345),(724,332),(721,320),(713,308),(704,306),(688,322),(674,333),
        (667,358),(639,378),(623,396),(636,417),(668,435),(695,444),(724,465),(733,477),(716,484),(694,480),(668,481),(649,473),(630,462),(618,445),(599,420),(589,391),(571,373),(560,354),(550,341),
        (537,347),(525,365),(515,380),(492,386),(476,400),(455,415),(448,435),(456,459),(474,473),(471,491),(456,499),(434,498),(419,493),(405,506),(385,504),(372,498),(368,477),(371,455),(377,433),(394,402),(412,384),(424,371),(442,358),(445,343),(445,333),(431,320),(410,310),(378,311),(350,314),(327,313),(307,304),(277,301),(240,308),(201,315),(173,326),(140,348),(114,371)
    ],np.int32)
    rough=np.zeros((h,w),np.uint8);cv2.fillPoly(rough,[outline],255)
    inside=cv2.erode(rough,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(15,15)))
    outside=cv2.dilate(rough,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(29,29)))
    mask=np.full((h,w),cv2.GC_BGD,dtype=np.uint8)
    mask[outside>0]=cv2.GC_PR_BGD
    mask[rough>0]=cv2.GC_PR_FGD
    mask[inside>0]=cv2.GC_FGD
    bg=np.zeros((1,65),np.float64);fg=np.zeros((1,65),np.float64)
    cv2.grabCut(img,mask,None,bg,fg,5,cv2.GC_INIT_WITH_MASK)
    alpha=np.where((mask==cv2.GC_FGD)|(mask==cv2.GC_PR_FGD),255,0).astype('uint8')
    n,labels,stats,_=cv2.connectedComponentsWithStats(alpha,8)
    if n>1:
        idx=1+np.argmax(stats[1:,cv2.CC_STAT_AREA]);alpha=np.where(labels==idx,255,0).astype('uint8')
    alpha=cv2.GaussianBlur(alpha,(3,3),.8)
    rgba=cv2.cvtColor(img,cv2.COLOR_BGR2RGBA);rgba[:,:,3]=alpha
    original=Image.fromarray(rgba)
    # Preserve anatomical proportions; place the dinosaur inside a 3:2 scene
    # with a baseline near the bottom and space for the status panels.
    scale=1.14
    sprite=original.resize((int(w*scale),int(h*scale)),Image.Resampling.LANCZOS)
    output=Image.new('RGBA',(1200,800),(0,0,0,0))
    output.paste(sprite,(-57,140),sprite)
    # `paste` with alpha mask produces premultiplied corners; keep RGBA.
    output.save(ROOT/'assets'/'trex_original.png',optimize=True)

    # Recreate background where the dinosaur stood, leaving only AI-generated
    # forest. Remove the source illustration's decorative UI labels/borders.
    inpaint=cv2.dilate((alpha>20).astype('uint8'),cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(55,55)))*255
    # Source illustration has a small black 'GIF' badge, generated by the tool.
    inpaint[35:115,1015:1127]=255
    inpaint[:33,:]=255
    sf=.33
    small=cv2.resize(img,(int(w*sf),int(h*sf)),interpolation=cv2.INTER_AREA)
    smask=cv2.resize(inpaint,(small.shape[1],small.shape[0]),interpolation=cv2.INTER_NEAREST)
    clean=cv2.inpaint(small,smask,22,cv2.INPAINT_TELEA)
    clean=cv2.resize(clean,(w,h),interpolation=cv2.INTER_CUBIC)
    clean=cv2.GaussianBlur(clean,(0,0),8)
    blend=cv2.GaussianBlur(inpaint,(0,0),15).astype('float32')/255
    clean=(clean.astype('float32')*blend[:,:,None]+img.astype('float32')*(1-blend[:,:,None])).clip(0,255).astype('uint8')
    # Exclude frame graphics and all UI labels. Crop greenery only.
    clean=clean[34:497,22:1138]
    clean=cv2.resize(clean,(1200,800),interpolation=cv2.INTER_CUBIC)
    clean=cv2.GaussianBlur(clean,(0,0),3)
    cv2.imwrite(str(ROOT/'assets'/'forest_original.png'),clean,[cv2.IMWRITE_PNG_COMPRESSION,7])
    print('Created independent AI-generated forest and T-Rex layers')
if __name__=='__main__':main()
